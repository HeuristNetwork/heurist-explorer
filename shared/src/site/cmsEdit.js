const VOID = new Set(['area', 'base', 'br', 'col', 'embed', 'hr', 'img', 'input', 'link', 'meta', 'source', 'track', 'wbr']);
const RAW_TAGS = new Set(['script', 'style', 'textarea']);
const HEADINGS = ['h1', 'h2', 'h3', 'h4', 'h5', 'h6'];
const ID_ALPHABET = 'abcdefghijklmnopqrstuvwxyz0123456789';
const MODULES = ['explorer', 'data', 'map', 'timeline', 'graph', 'recordview'];

/**
 * Parse an HTML fragment into a tree: `{type: 'element', tag, attrs: [[name, value]], children, raw?}` and
 * `{type: 'text', text}` (text, comments). Text blocks, hosts and script/style keep their inner HTML in `raw`.
 *
 * @param {string} html
 * @returns {{type: 'root', children: Array<object>}}
 */
export function parseCmsHtml(html) {
  const root = { type: 'root', children: [] };
  const source = String(html ?? '');
  const stack = [root];
  const pattern = /<!--[\s\S]*?-->|<\/([a-zA-Z][\w:-]*)\s*>|<([a-zA-Z][\w:-]*)((?:\s+[^\s"'>/=]+(?:\s*=\s*(?:"[^"]*"|'[^']*'|[^\s"'=<>`]+))?)*)\s*(\/?)>/g;
  let last = 0;
  let match;
  const top = () => stack[stack.length - 1];
  const addText = (text) => { if (text) top().children.push({ type: 'text', text }); };
  while ((match = pattern.exec(source))) {
    addText(source.slice(last, match.index));
    last = pattern.lastIndex;
    if (match[0].startsWith('<!--')) {
      addText(match[0]);
    } else if (match[1]) {
      const tag = match[1].toLowerCase();
      const index = stack.findLastIndex((node) => node.tag === tag);
      if (index > 0) stack.length = index; // closes it and anything left open inside
    } else {
      const tag = match[2].toLowerCase();
      const element = { type: 'element', tag, attrs: parseAttributes(match[3] || ''), children: [] };
      top().children.push(element);
      if (VOID.has(tag) || match[4] === '/') continue;
      if (RAW_TAGS.has(tag) || hasAttr(element, 'data-h-text') || hasAttr(element, 'data-h-instance')) {
        const end = closingIndex(source, tag, last);
        element.raw = source.slice(last, end.start);
        last = end.end;
        pattern.lastIndex = last;
        continue;
      }
      stack.push(element);
    }
  }
  addText(source.slice(last));
  return root;
}

/**
 * HTML of a tree (or of one element).
 *
 * @param {object} node Root, element or text.
 * @returns {string}
 */
export function serializeCmsHtml(node) {
  if (!node) return '';
  if (node.type === 'text') return node.text;
  if (node.type === 'root') return node.children.map(serializeCmsHtml).join('');
  const attrs = node.attrs.map(([name, value]) => ` ${name}="${escapeAttr(value)}"`).join('');
  if (VOID.has(node.tag)) return `<${node.tag}${attrs}>`;
  const inner = node.raw !== undefined ? node.raw : node.children.map(serializeCmsHtml).join('');
  return `<${node.tag}${attrs}>${inner}</${node.tag}>`;
}

/** A new node or instance id that is not in `used`: prefix + 6 characters (as WebsiteStarter::id). */
export function newCmsId(prefix, used = new Set()) {
  for (;;) {
    let id = prefix;
    for (let index = 0; index < 6; index++) id += ID_ALPHABET[Math.floor(Math.random() * ID_ALPHABET.length)];
    if (!used.has(id)) return id;
  }
}

/** Editable website or page record: its HTML parts, configuration and translations. */
export class CmsRecordDocument {
  /**
   * @param {object} options
   * @param {Object<string, string>} options.parts HTML by part: `content`, and `header` / `footer` for a website.
   * @param {string|object} [options.config] Configuration (2-1187), JSON or object.
   * @param {Object<string, Object<string, string>>} [options.translations] Language => {node id: html}.
   */
  constructor({ parts = {}, config = '', translations = {} } = {}) {
    this.roots = {};
    for (const name of CMS_PARTS) {
      if (typeof parts[name] === 'string') this.roots[name] = parseCmsHtml(parts[name]);
    }
    const parsed = typeof config === 'string' ? parseCmsConfig(config) : { config: clone(config), issues: [] };
    this.config = parsed.config;
    this.config.instances = isMap(this.config.instances) ? this.config.instances : {};
    this.config.styles = isMap(this.config.styles) ? this.config.styles : {};
    this.config.media = isMap(this.config.media) ? this.config.media : {};
    this.configIssues = parsed.issues;
    this.translations = clone(isMap(translations) ? translations : {});
  }

  /** Part names of this record, in page order. */
  partNames() {
    return CMS_PARTS.filter((name) => this.roots[name]);
  }

  /**
   * A snapshot of the whole document (undo).
   *
   * @returns {string}
   */
  snapshot() {
    return JSON.stringify({ roots: this.roots, config: this.config, translations: this.translations });
  }

  /** Go back to a snapshot. */
  restore(snapshot) {
    const state = JSON.parse(snapshot);
    this.roots = state.roots;
    this.config = state.config;
    this.translations = state.translations;
  }

  /**
   * Values to save: HTML of the parts, the configuration JSON and the translations by language.
   *
   * @returns {{parts: Object<string, string>, configuration: string, translations: Object<string, object>}}
   */
  serialize() {
    const parts = {};
    for (const name of this.partNames()) parts[name] = serializeCmsHtml(this.roots[name]);
    const config = { ...this.config, schema: CMS_SCHEMA };
    for (const key of ['instances', 'styles']) if (isMap(config[key]) && !Object.keys(config[key]).length) config[key] = {};
    if (isMap(config.media) && !Object.keys(config.media).length) delete config.media;
    const translations = {};
    for (const [language, blocks] of Object.entries(this.translations)) {
      // a copy: the serialized state is the saved state of the designer, `setTranslation` changes the live blocks
      if (isMap(blocks) && Object.keys(blocks).length) translations[language] = { ...blocks };
    }
    return { parts, configuration: JSON.stringify(config), translations };
  }

  /**
   * HTML of a part, with the translations of a language put into the text blocks (preview).
   *
   * @param {string} part
   * @param {string|null} [language] Language of the translations; null = the original.
   */
  html(part, language = null) {
    const root = this.roots[part];
    if (!root) return '';
    const texts = language ? this.translations[language] || {} : null;
    if (!texts || !Object.keys(texts).length) return serializeCmsHtml(root);
    const copy = clone(root);
    walk(copy, (node) => {
      const id = attr(node, 'data-h-node');
      if (hasAttr(node, 'data-h-text') && id && typeof texts[id] === 'string') node.raw = texts[id];
    });
    return serializeCmsHtml(copy);
  }

  /**
   * The structure tree of a part: nodes with their kind, label and children.
   *
   * @param {string} part
   * @returns {Array<{id: string, kind: string, tag: string, label: string, control: string|null, instance: string|null,
   *          media: string|null, type: string|null, preset: string|null, configured: boolean, caption: string|null,
   *          children: Array}>}
   *          caption: node id of the caption of a group (not an item itself).
   */
  tree(part) {
    const root = this.roots[part];
    return root ? this._items(root) : [];
  }

  _items(container) {
    const items = [];
    const caption = captionOf(container);
    for (const child of container.children) {
      if (child.type !== 'element' || child === caption) continue;
      const id = attr(child, 'data-h-node');
      if (!id) {
        items.push(...this._items(child)); // a wrapper without an id: its nodes go up
        continue;
      }
      const instanceId = attr(child, 'data-h-instance');
      const instance = instanceId ? this.config.instances[instanceId] : null;
      items.push({
        id,
        kind: kindOf(child),
        tag: child.tag,
        label: labelOf(child, instance),
        control: attr(child, 'data-h-control'),
        instance: instanceId,
        media: attr(child, 'data-h-media'),
        field: attr(child, 'data-h-field'),
        // a field reference without text in the snapshot (the server writes the value): the designer shows the field name
        fieldOnly: Boolean(attr(child, 'data-h-field')) && hasAttr(child, 'data-h-text') && !plain(child.raw || ''),
        type: instance?.type || null,
        preset: attr(child, 'data-h-style'),
        configured: instanceId ? isConfigured(instance) : !hasAttr(child, 'data-h-media') || Boolean(this.media(id)?.settings.file),
        caption: attr(captionOf(child), 'data-h-node'),
        children: child.raw === undefined ? this._items(child) : []
      });
    }
    return items;
  }

  /**
   * An element by node id: the element, its parent and part.
   *
   * @returns {{node: object, parent: object, part: string}|null}
   */
  find(id) {
    for (const part of this.partNames()) {
      const found = findNode(this.roots[part], id);
      if (found) return { ...found, part };
    }
    return null;
  }

  /** Whether an element (node id; null = the part root) takes children. */
  isContainer(id) {
    if (id == null) return true;
    const node = this.find(id)?.node;
    return Boolean(node) && node.raw === undefined && CMS_CONTROLS.includes(attr(node, 'data-h-control'));
  }

  /**
   * Whether a node may be put at a place: inside a container (last child), or before / after a node. Never into
   * itself or one of its descendants.
   *
   * @param {string} id Node to move.
   * @param {{id: string|null, position: 'inside'|'before'|'after', part?: string}} target
   */
  canDrop(id, target) {
    const moving = this.find(id);
    if (!moving) return false;
    if (target.id === id) return false;
    if (target.id != null && findNode(moving.node, target.id)) return false;
    if (target.position === 'inside') return this.isContainer(target.id);
    return target.id != null && Boolean(this.find(target.id));
  }

  /**
   * Add an element (§5.2) at a place: inside the target container (last child), before or after the target node.
   *
   * @param {string} part Part of the place when the target is the root.
   * @param {string} element One of CMS_ELEMENTS.
   * @param {{id: string|null, position: 'inside'|'before'|'after'}} target
   * @param {object} [options] `blocks` of the footer composer (siteFooter), `year` of its copyright.
   * @returns {string} Node id of the new element.
   */
  insertElement(part, element, target = { id: null, position: 'inside' }, options = {}) {
    const node = this._create(element, options);
    this._place(part, node, target);
    return attr(node, 'data-h-node');
  }

  /**
   * Move a node.
   *
   * @param {string} id
   * @param {{id: string|null, position: 'inside'|'before'|'after', part?: string}} target
   * @returns {boolean} False when the place is not allowed.
   */
  move(id, target) {
    if (!this.canDrop(id, target)) return false;
    const moving = this.find(id);
    removeChild(moving.parent, moving.node);
    this._place(target.part || moving.part, moving.node, target);
    if (hasAttr(moving.node, 'data-h-control')) this._removeEmpty(moving.parent);
    return true;
  }

  /**
   * Remove a node with its descendants, their node styles, translations and instances. A group, tabs or
   * accordion left without elements (its caption only) when a group is removed or moved out of it goes too.
   *
   * @returns {boolean}
   */
  remove(id) {
    const found = this.find(id);
    if (!found) return false;
    removeChild(found.parent, found.node);
    this._forget(found.node);
    if (hasAttr(found.node, 'data-h-control')) this._removeEmpty(found.parent);
    return true;
  }

  /**
   * Add a panel (a group with a caption and a text) at the end of tabs or an accordion.
   *
   * @param {string} id Tabs or accordion.
   * @returns {string|null} Node id of the new panel.
   */
  addPanel(id) {
    const node = this.find(id)?.node;
    const control = node ? attr(node, 'data-h-control') : null;
    if (control !== 'tabs' && control !== 'accordion') return null;
    const panel = this._panel(control, node.children.filter((child) => child.type === 'element').length + 1, this._usedIds());
    node.children.push(panel);
    return attr(panel, 'data-h-node');
  }

  /**
   * Caption of a group: node id, plain text and translations (language => plain text), or null.
   *
   * @param {string} id Group.
   * @returns {{id: string, text: string, translations: Object<string, string>}|null}
   */
  caption(id) {
    const node = captionOf(this.find(id)?.node);
    if (!node) return null;
    const captionId = attr(node, 'data-h-node');
    const translations = {};
    for (const [language, blocks] of Object.entries(this.translations)) {
      if (typeof blocks?.[captionId] === 'string') translations[language] = plain(blocks[captionId]);
    }
    return { id: captionId, text: plain(node.raw || ''), translations };
  }

  /** Whether a node is a panel of tabs or an accordion (its caption is the panel label). */
  isPanel(id) {
    const found = this.find(id);
    return Boolean(found) && ['tabs', 'accordion'].includes(attr(found.parent, 'data-h-control'));
  }

  /**
   * Set the caption of a group (plain text) and its translations. A new caption is an `h3` (`summary` in
   * `details`); an empty text removes it, but not on a panel of tabs or an accordion (it is the panel label).
   * A group with a caption is a `section` labelled by its caption (`aria-labelledby`), without one a `div`
   * (§20; panels keep their tags).
   *
   * @param {string} id Group.
   * @param {string} text
   * @param {Object<string, string>} [translations] Language => plain text (empty = no translation).
   * @returns {boolean} False when nothing was set.
   */
  setCaption(id, text, translations = {}) {
    const found = this.find(id);
    if (!found || attr(found.node, 'data-h-control') !== 'group' || found.node.raw !== undefined) return false;
    const panel = this.isPanel(id);
    let caption = captionOf(found.node);
    const value = String(text ?? '').trim();
    if (!value) {
      if (!caption || panel) return false;
      removeChild(found.node, caption);
      this._forget(caption);
      if (found.node.tag === 'section') found.node.tag = 'div';
      removeAttr(found.node, 'aria-labelledby');
      return true;
    }
    if (!caption) {
      const tag = found.node.tag === 'details' ? 'summary' : 'h3';
      caption = element$(tag, [['data-h-node', newCmsId('n', this._usedIds())], ['data-h-text', '']], '');
      found.node.children.unshift(caption);
    }
    if (!panel && found.node.tag === 'div') found.node.tag = 'section';
    if (!panel) labelSection(found.node);
    caption.raw = escapeText(value);
    const captionId = attr(caption, 'data-h-node');
    for (const [language, translation] of Object.entries(translations || {})) {
      const translated = String(translation ?? '').trim();
      this.setTranslation(language, captionId, translated ? escapeText(translated) : '');
    }
    return true;
  }

  /**
   * The group of a caption (a click on a caption in the preview selects its group).
   *
   * @param {string} id Node id.
   * @returns {string|null} Node id of the group, or null when the node is not a caption.
   */
  captionGroup(id) {
    const found = this.find(id);
    if (!found?.parent || captionOf(found.parent) !== found.node) return null;
    return attr(found.parent, 'data-h-node');
  }

  /** Forget the node styles, translations and instances of a removed node and its descendants. */
  _forget(node) {
    const { nodes, instances, media } = idsIn(node);
    for (const nodeId of nodes) {
      if (isMap(this.config.styles.nodes)) delete this.config.styles.nodes[nodeId];
      for (const blocks of Object.values(this.translations)) if (isMap(blocks)) delete blocks[nodeId];
    }
    const hosts = this._instanceHosts();
    for (const instanceId of instances) if (!hosts.has(instanceId)) delete this.config.instances[instanceId];
    const elements = this._mediaElements();
    for (const mediaId of media) if (!elements.has(mediaId)) delete this.config.media[mediaId];
  }

  /** Remove a control that has no elements left but its caption (then its parent the same way). */
  _removeEmpty(container) {
    const id = container?.type === 'element' ? attr(container, 'data-h-node') : null;
    if (!id || !hasAttr(container, 'data-h-control')) return;
    const caption = captionOf(container);
    if (container.children.some((child) => child.type === 'element' && child !== caption)) return;
    this.remove(id);
  }

  /**
   * Copy a node (§5.3). *structure*: containers and text blocks with styles and presets, texts empty;
   * *all*: with texts and translations. Instances become new instances of the same type with default settings.
   *
   * @param {string} id
   * @param {'structure'|'all'} [mode]
   * @returns {object|null} Clipboard value, or null (an instance alone can not be copied).
   */
  copy(id, mode = 'all') {
    const found = this.find(id);
    if (!found || hasAttr(found.node, 'data-h-instance')) return null;
    const node = clone(found.node);
    const styles = {};
    const translations = {};
    const instances = {};
    const media = {};
    walk(node, (element) => {
      const nodeId = attr(element, 'data-h-node');
      if (nodeId && isMap(this.config.styles.nodes?.[nodeId])) styles[nodeId] = clone(this.config.styles.nodes[nodeId]);
      // a media element is copied with its file and settings (static content), also in structure mode
      const mediaId = attr(element, 'data-h-media');
      if (mediaId && isMap(this.config.media[mediaId])) media[mediaId] = clone(this.config.media[mediaId]);
      if (hasAttr(element, 'data-h-text')) {
        if (mode === 'structure' && !mediaId) {
          element.raw = placeholderText(element);
        } else if (nodeId) {
          for (const [language, blocks] of Object.entries(this.translations)) {
            if (typeof blocks?.[nodeId] === 'string') (translations[language] ||= {})[nodeId] = blocks[nodeId];
          }
        }
      }
      const instanceId = attr(element, 'data-h-instance');
      if (instanceId) {
        const instance = this.config.instances[instanceId];
        instances[instanceId] = { kind: instance?.kind || 'module', type: instance?.type || 'data' };
      }
    });
    return { format: 'heurist-cms-clip', mode, sourceId: id, html: serializeCmsHtml(node), styles, translations, instances, media };
  }

  /**
   * Paste a clipboard value with new ids. Not into the copied node itself or one of its descendants.
   *
   * @param {object} clip Value of copy().
   * @param {string} part Part of the place when the target is the root.
   * @param {{id: string|null, position: 'inside'|'before'|'after'}} target The copied element or a place inside it means:
   *        after the copied element, as its sibling.
   * @returns {string|null} Node id of the pasted element, or null when the place is not allowed.
   */
  paste(clip, part, target) {
    if (clip?.format !== 'heurist-cms-clip') return null;
    const source = clip.sourceId ? this.find(clip.sourceId) : null;
    if (source && target.id != null && findNode(source.node, target.id)) target = { id: clip.sourceId, position: 'after' };
    if (target.position === 'inside' ? !this.isContainer(target.id) : !this.find(target.id)) return null;
    const node = parseCmsHtml(clip.html).children.find((child) => child.type === 'element');
    if (!node) return null;
    const used = this._usedIds();
    walk(node, (element) => {
      const oldId = attr(element, 'data-h-node');
      if (oldId) {
        const nodeId = newCmsId('n', used);
        used.add(nodeId);
        setAttr(element, 'data-h-node', nodeId);
        if (isMap(clip.styles?.[oldId])) this._nodeStyles()[nodeId] = clone(clip.styles[oldId]);
        for (const [language, blocks] of Object.entries(clip.translations || {})) {
          if (typeof blocks?.[oldId] === 'string') (this.translations[language] ||= {})[nodeId] = blocks[oldId];
        }
      }
      const oldInstance = attr(element, 'data-h-instance');
      if (oldInstance) {
        const instanceId = newCmsId('i', used);
        used.add(instanceId);
        setAttr(element, 'data-h-instance', instanceId);
        element.raw = '';
        const { kind, type } = clip.instances?.[oldInstance] || { kind: 'module', type: 'data' };
        this.config.instances[instanceId] = defaultInstance(kind, type);
      }
      const oldMedia = attr(element, 'data-h-media');
      if (oldMedia) {
        const mediaId = newCmsId('m', used);
        used.add(mediaId);
        setAttr(element, 'data-h-media', mediaId);
        this.config.media[mediaId] = clone(isMap(clip.media?.[oldMedia]) ? clip.media[oldMedia] : CMS_MEDIA_DEFAULTS);
      }
    });
    // the label of a pasted section follows the new id of its caption
    walk(node, (element) => { if (hasAttr(element, 'aria-labelledby')) labelSection(element); });
    this._place(part, node, target);
    return attr(node, 'data-h-node');
  }

  /** Inner HTML of a text block. */
  text(id) {
    const node = this.find(id)?.node;
    return node && hasAttr(node, 'data-h-text') ? node.raw || '' : '';
  }

  /**
   * A media element (§33): its media id, settings (configuration `media`), HTML and translations (language => HTML).
   *
   * @param {string} id Node id.
   * @returns {{mediaId: string, settings: object, html: string, translations: Object<string, string>}|null}
   */
  media(id) {
    const node = this.find(id)?.node;
    const mediaId = node ? attr(node, 'data-h-media') : null;
    if (!mediaId) return null;
    const translations = {};
    for (const [language, blocks] of Object.entries(this.translations)) {
      if (typeof blocks?.[id] === 'string') translations[language] = blocks[id];
    }
    return { mediaId, settings: { ...CMS_MEDIA_DEFAULTS, ...(this.config.media[mediaId] || {}) }, html: node.raw || '', translations };
  }

  /**
   * Set a media element: its settings, the HTML made from them and the HTML of each language of the website.
   *
   * @param {string} id Node id.
   * @param {{settings: object, html: string, translations?: Object<string, string>, view?: {type: string, url: string}|null}} value
   *        `view`: what the action Player / Viewer opens (cmsMediaView), the same for all languages. Languages left out lose
   *        their translation.
   * @returns {boolean}
   */
  setMedia(id, { settings, html, translations = {}, view = null }) {
    const node = this.find(id)?.node;
    const mediaId = node ? attr(node, 'data-h-media') : null;
    if (!mediaId) return false;
    this.config.media[mediaId] = { ...CMS_MEDIA_DEFAULTS, ...settings };
    node.raw = String(html ?? '');
    if (view) {
      setAttr(node, 'data-h-view', view.type);
      setAttr(node, 'data-h-full', view.url);
    } else {
      removeAttr(node, 'data-h-view');
      removeAttr(node, 'data-h-full');
    }
    for (const language of Object.keys(this.translations)) if (!Object.hasOwn(translations, language)) this.setTranslation(language, id, '');
    for (const [language, text] of Object.entries(translations)) this.setTranslation(language, id, String(text ?? ''));
    return true;
  }

  /**
   * The field of a text block (plan 27e).
   *
   * @param {string} id Node id.
   * @returns {string|null} `data-h-field`.
   */
  field(id) {
    const node = this.find(id)?.node;
    return node ? attr(node, 'data-h-field') : null;
  }

  /**
   * Set or remove the field of a text block. The value comes from the record: the translations of the block are removed.
   *
   * @param {string} id Node id.
   * @param {string|null} reference `207439.2-1`, `website.2-1`; null: typed text again.
   * @param {string} [html] The last resolved value (snapshot).
   * @returns {boolean}
   */
  setField(id, reference, html = '') {
    const node = this.find(id)?.node;
    if (!node || !hasAttr(node, 'data-h-text') || hasAttr(node, 'data-h-media')) return false;
    node.attrs = node.attrs.filter(([name]) => name !== 'data-h-field');
    if (reference) {
      node.attrs.push(['data-h-field', reference]);
      node.raw = String(html ?? '');
      for (const language of Object.keys(this.translations)) this.setTranslation(language, id, '');
    }
    return true;
  }

  /** Set the inner HTML of a text block. */
  setText(id, html) {
    const node = this.find(id)?.node;
    if (!node || !hasAttr(node, 'data-h-text')) return false;
    node.raw = String(html ?? '');
    return true;
  }

  /** Translation of a text block, or ''. */
  translation(language, id) {
    return String(this.translations[language]?.[id] ?? '');
  }

  /** Set (or remove with an empty value) the translation of a text block. */
  setTranslation(language, id, html) {
    const text = String(html ?? '');
    if (!text.trim()) {
      if (this.translations[language]) delete this.translations[language][id];
      return;
    }
    (this.translations[language] ||= {})[id] = text;
  }

  /**
   * The group an element is in (not tabs or accordions): its node id and preset (`data-h-style`).
   *
   * @param {string} id
   * @returns {{id: string, preset: string|null}|null}
   */
  parentGroup(id) {
    const parent = this.find(id)?.parent;
    if (!parent || parent.type !== 'element' || attr(parent, 'data-h-control') !== 'group' || !hasAttr(parent, 'data-h-node')) return null;
    return { id: attr(parent, 'data-h-node'), preset: attr(parent, 'data-h-style') || null };
  }

  /** Own style of a node (a copy), or {}. */
  nodeStyle(id) {
    return clone(this.config.styles.nodes?.[id] || {});
  }

  /** Set the own style of a node; an empty style removes it. */
  setNodeStyle(id, style) {
    if (isMap(style) && Object.keys(style).length) {
      this._nodeStyles()[id] = clone(style);
    } else if (isMap(this.config.styles.nodes)) {
      delete this.config.styles.nodes[id];
    }
  }

  /** Set the preset of a node (`data-h-style`); null removes it. */
  setPreset(id, name) {
    const node = this.find(id)?.node;
    if (!node) return false;
    if (name) setAttr(node, 'data-h-style', name); else removeAttr(node, 'data-h-style');
    return true;
  }

  /** The class attribute of a node (custom CSS classes of the user's own rules), or ''. */
  cssClass(id) {
    return attr(this.find(id)?.node, 'class') || '';
  }

  /** Set the class attribute of a node; an empty value removes it. */
  setCssClass(id, value) {
    const node = this.find(id)?.node;
    if (!node) return false;
    const text = String(value ?? '').trim().split(/\s+/).filter(Boolean).join(' ');
    if (text) setAttr(node, 'class', text); else removeAttr(node, 'class');
    return true;
  }

  /** Kind defaults (`styles.kinds`, a copy). */
  kinds() {
    return clone(this.config.styles.kinds || {});
  }

  /** Presets (`styles.presets`, a copy). */
  presets() {
    return clone(this.config.styles.presets || {});
  }

  /** Base settings (`styles.base`, a copy). */
  base() {
    return clone(this.config.styles.base || {});
  }

  /** Layout settings (`layout`, plan 27f: navigation mode, header / footer; a page: hide flags), a copy. */
  layout() {
    return clone(isMap(this.config.layout) ? this.config.layout : {});
  }

  /** Replace the layout settings; empty removes the key. */
  setLayout(layout) {
    if (isMap(layout) && Object.keys(layout).length) this.config.layout = clone(layout); else delete this.config.layout;
  }

  /** Replace kind defaults, presets and / or base settings (the Styles dialog). */
  setCommonStyles({ base, kinds, presets } = {}) {
    if (base !== undefined) this.config.styles.base = clone(base || {});
    if (kinds !== undefined) this.config.styles.kinds = clone(kinds || {});
    if (presets !== undefined) this.config.styles.presets = clone(presets || {});
  }

  /** Configuration of an instance (a copy), or null. */
  instance(instanceId) {
    const instance = this.config.instances[instanceId];
    return instance ? clone(instance) : null;
  }

  /** Set the settings and state of an instance. */
  setInstance(instanceId, { settings, state } = {}) {
    const instance = this.config.instances[instanceId];
    if (!instance) return false;
    if (settings !== undefined) instance.settings = clone(settings || {});
    if (state !== undefined) instance.state = state == null ? null : clone(state);
    return true;
  }

  /**
   * Problems of the record (checkCmsDocument).
   *
   * @param {string} [baseUrl] Heurist base URL (background images).
   * @param {string[]} [otherInstances] Instances configured on the website (a page's header menu...).
   */
  check(baseUrl = '', otherInstances = []) {
    const parts = this.partNames().map((name) => serializeCmsHtml(this.roots[name]));
    return [...this.configIssues, ...checkCmsDocument(this.config, parts, this.translations, baseUrl, otherInstances)];
  }

  _create(element, options = {}) {
    const used = this._usedIds();
    const id = (prefix) => {
      const value = newCmsId(prefix, used);
      used.add(value);
      return value;
    };
    const text = () => element$('div', [['data-h-node', id('n')], ['data-h-text', '']], '<p>Text</p>');
    const group = (children = [], preset = null) => {
      const attrs = [['data-h-node', id('n')], ['data-h-control', 'group']];
      if (preset) attrs.push(['data-h-style', preset]);
      return element$('div', attrs, undefined, children);
    };
    // columns: an own style (a grid of equal columns, one column on narrow screens; plan 27c §31), so they do not
    // depend on the presets of the website; the texts need no style
    const columns = (count, preset) => {
      const node = group(Array.from({ length: count }, text), preset);
      this._nodeStyles()[attr(node, 'data-h-node')] = {
        display: 'grid', 'grid-template-columns': `repeat(${count}, minmax(0, 1fr))`, gap: '12px',
        narrow: { 'grid-template-columns': '1fr' }
      };
      return node;
    };
    switch (element) {
      case 'text': return text();
      // a text block with the value of a field of a record (plan 27e §22): `setField` gives its reference and snapshot
      case 'field': return element$('div', [['data-h-node', id('n')], ['data-h-text', ''], ['data-h-field', '']], '');
      case 'media': {
        // a figure (text block) whose HTML the designer makes from the file and the settings (§33)
        const mediaId = id('m');
        this.config.media[mediaId] = { ...CMS_MEDIA_DEFAULTS };
        return element$('figure', [['data-h-node', id('n')], ['data-h-media', mediaId], ['data-h-text', '']], '');
      }
      case 'group': return group();
      case 'columns2': return columns(2, 'columns2');
      case 'columns3': return columns(3, 'columns3');
      case 'tabs':
      case 'accordion':
        return element$('div', [['data-h-node', id('n')], ['data-h-control', element]], undefined, [1, 2].map((number) =>
          this._panel(element, number, used)));
      case 'report':
      case 'cards':
      case 'gallery': {
        const instanceId = id('i');
        const nodeId = id('n');
        this.config.instances[instanceId] = defaultInstance('widget', element);
        this._nodeStyles()[nodeId] = { 'min-height': '0' };
        return element$('div', [['data-h-node', nodeId], ['data-h-instance', instanceId]], '');
      }
      case 'headerSet':
        return this._header(id, group);
      case 'siteFooter':
        return this._footer(options, id, group);
      case 'language':
      case 'actionmenu':
      case 'social':
      case 'badges': {
        // helper widgets (plan 27f): language switch, action menu (social media = its preset), badges; widget hosts
        // without the min-height of the instance kind
        const instanceId = id('i');
        const nodeId = id('n');
        const instance = defaultInstance('widget', element === 'social' ? 'actionmenu' : element);
        if (element === 'social') instance.settings = { preset: 'social', presentation: 'icons', items: [] };
        this.config.instances[instanceId] = instance;
        this._nodeStyles()[nodeId] = { 'min-height': '0' };
        return element$(element === 'language' ? 'div' : 'nav', [['data-h-node', nodeId], ['data-h-instance', instanceId]], '');
      }
      case 'menu': {
        const instanceId = id('i');
        const nodeId = id('n');
        this.config.instances[instanceId] = defaultInstance('widget', 'menu');
        // a widget host: not the min-height of the instance kind (WebsiteStarter does the same)
        this._nodeStyles()[nodeId] = { 'min-height': '0' };
        return element$('nav', [['data-h-node', nodeId], ['data-h-instance', instanceId]], '');
      }
      default: {
        if (!MODULES.includes(element)) throw new Error(`Unknown element "${element}"`);
        const instanceId = id('i');
        this.config.instances[instanceId] = defaultInstance('module', element);
        return element$('div', [['data-h-node', id('n')], ['data-h-instance', instanceId]], '');
      }
    }
  }

  /**
   * The header default set (plan 27f §13): logo, title and subtitle of the website record, the main menu and the
   * language switch. No own styles: the CSS of the website arranges them by their classes (one row on normal screens,
   * two rows on medium screens or with `layout.header.rows = two`, stacked on narrow screens, a column in a vertical
   * header); the banner image of the website is the background of the header.
   */
  _header(id, group) {
    const field = (code, className, html = '') => element$('div', [['data-h-node', id('n')], ['data-h-text', ''],
      ['data-h-field', `website.${code}`], ['class', className]], html);
    const classed = (node, className) => {
      setAttr(node, 'class', className);
      return node;
    };
    const menu = this._create('menu');
    // vertical in a vertical header
    this.config.instances[attr(menu, 'data-h-instance')].settings = { orientation: 'auto' };
    return classed(group([
      field(CMS_HEADER_FIELDS.logo, 'h-site-logo'),
      classed(group([field(CMS_HEADER_FIELDS.title, 'h-site-title', 'Website title'), field(CMS_HEADER_FIELDS.subtitle, 'h-site-subtitle')]),
        'h-site-brand'),
      classed(menu, 'h-site-hset-menu'),
      classed(this._create('language'), 'h-site-hset-lang')
    ]), 'h-site-hset');
  }

  /**
   * The footer of the footer composer (plan 27f §3.2): the chosen blocks in columns (one column on narrow screens),
   * ordinary elements to change afterwards. Copyright, powered by Heurist and hosted at are texts in one group (review
   * 2026-11-10); hosted at only when the installation has a host organisation (`host`, HostInfo of the server).
   *
   * @param {{blocks?: string[], year?: number, baseUrl?: string, host?: {logo: string, url: ?string}|null}} options
   */
  _footer({ blocks = ['social', 'links', 'copyright', 'heurist', 'host'], year = new Date().getFullYear(), baseUrl = '', host = null } = {},
    id, group) {
    const style = (node, value) => {
      this._nodeStyles()[attr(node, 'data-h-node')] = value;
      return node;
    };
    const text = (html) => element$('div', [['data-h-node', id('n')], ['data-h-text', '']], html);
    const widget = (element, settings = null) => {
      const node = this._create(element);
      if (settings) Object.assign(this.config.instances[attr(node, 'data-h-instance')].settings, settings);
      return node;
    };
    const block = (children) => style(group(children), { display: 'flex', 'flex-direction': 'column', gap: '0.5rem' });
    const made = {
      badges: () => block([text('<p><strong>Partners and sponsors</strong></p>'), widget('badges')]),
      social: () => block([text('<p><strong>Follow us</strong></p>'), widget('social')]),
      links: () => block([widget('actionmenu', { presentation: 'links' })])
    };
    const credits = {
      copyright: () => text(`<p>© ${year} Website title</p>`),
      heurist: () => text(cmsPoweredBy(baseUrl)),
      host: () => (host?.logo ? text(cmsHostedAt(host)) : null)
    };
    const chosen = CMS_FOOTER_BLOCKS.filter((name) => blocks.includes(name));
    const lines = chosen.filter((name) => credits[name]).map((name) => credits[name]()).filter(Boolean);
    const children = chosen.filter((name) => made[name]).map((name) => made[name]());
    if (lines.length) children.push(block(lines));
    return style(group(children), {
      display: 'grid', 'grid-template-columns': `repeat(${Math.max(1, Math.min(children.length, 4))}, minmax(0, 1fr))`, gap: '16px',
      padding: '1rem', 'align-items': 'start', narrow: { 'grid-template-columns': '1fr' }
    });
  }

  /** A panel of tabs (`section` with an `h3` caption) or of an accordion (`details` with `summary`), with a text. */
  _panel(control, number, used) {
    const id = () => {
      const value = newCmsId('n', used);
      used.add(value);
      return value;
    };
    const tabs = control === 'tabs';
    const caption = element$(tabs ? 'h3' : 'summary', [['data-h-node', id()], ['data-h-text', '']], `${tabs ? 'Tab' : 'Section'} ${number}`);
    const text = element$('div', [['data-h-node', id()], ['data-h-text', '']], '<p>Text</p>');
    return element$(tabs ? 'section' : 'details', [['data-h-node', id()], ['data-h-control', 'group']], undefined, [caption, text]);
  }

  _place(part, node, target) {
    let parent;
    let index;
    if (target.position === 'inside') {
      parent = target.id == null ? this.roots[part] : this.find(target.id)?.node;
      if (!parent) throw new Error(`No part or container for ${target.id ?? part}`);
      index = parent.children.length;
    } else {
      const found = this.find(target.id);
      if (!found) throw new Error(`No node ${target.id}`);
      parent = found.parent;
      index = parent.children.indexOf(found.node) + (target.position === 'after' ? 1 : 0);
    }
    parent.children.splice(index, 0, node);
  }

  _nodeStyles() {
    if (!isMap(this.config.styles.nodes)) this.config.styles.nodes = {};
    return this.config.styles.nodes;
  }

  _usedIds() {
    const used = new Set([...Object.keys(this.config.instances), ...Object.keys(this.config.media)]);
    for (const part of this.partNames()) {
      const { nodes, instances, media } = idsIn(this.roots[part]);
      for (const value of [...nodes, ...instances, ...media]) used.add(value);
    }
    return used;
  }

  _mediaElements() {
    const elements = new Set();
    for (const part of this.partNames()) for (const value of idsIn(this.roots[part]).media) elements.add(value);
    return elements;
  }

  _instanceHosts() {
    const hosts = new Set();
    for (const part of this.partNames()) for (const value of idsIn(this.roots[part]).instances) hosts.add(value);
    return hosts;
  }
}

/**
 * Content and configuration of a new page from a page preset (plan 27c §4).
 *
 * @param {string} preset One of CMS_PAGE_PRESETS.
 * @param {string} title Page title (the first heading).
 * @returns {{content: string, configuration: string}}
 */
export function cmsPageStarter(preset, title) {
  const doc = new CmsRecordDocument({ parts: { content: '' }, config: { schema: CMS_SCHEMA, instances: {}, styles: {} } });
  const heading = doc.insertElement('content', 'text');
  doc.setText(heading, `<h1>${escapeText(title || 'Page')}</h1>`);
  if (preset === 'team') {
    // the template Team (plan 27e): a grid of cards made by the Smarty report of a team member; the user picks the records
    const grid = doc.insertElement('content', 'group');
    doc.setNodeStyle(grid, { display: 'grid', 'grid-template-columns': 'repeat(auto-fill, minmax(240px, 1fr))', gap: '16px' });
    const cards = doc.insertElement('content', 'cards', { id: grid, position: 'inside' });
    const instanceId = doc.find(cards).node.attrs.find(([name]) => name === 'data-h-instance')[1];
    doc.setInstance(instanceId, { settings: { mode: 'manual', query: null, template: CMS_TEAM_TEMPLATE, presentation: 'list', action: 'none' } });
  } else if (preset === 'blank') {
    // one text element: the title and a paragraph (plan 27c §19)
    doc.setText(heading, `<h1>${escapeText(title || 'Page')}</h1><p>Text</p>`);
  } else if (preset === 'columns2' || preset === 'textColumns2') {
    if (preset === 'textColumns2') doc.insertElement('content', 'text');
    doc.insertElement('content', 'columns2');
  } else if (preset === 'columns3' || preset === 'textColumns3') {
    if (preset === 'textColumns3') doc.insertElement('content', 'text');
    doc.insertElement('content', 'columns3');
  } else {
    doc.insertElement('content', 'text');
  }
  const { parts, configuration } = doc.serialize();
  return { content: parts.content, configuration };
}

/** Kind of an element: control, text, instance or other. */
function kindOf(node) {
  if (hasAttr(node, 'data-h-instance')) return 'instance';
  if (hasAttr(node, 'data-h-media')) return 'media';
  if (hasAttr(node, 'data-h-text')) return 'text';
  if (hasAttr(node, 'data-h-control')) return 'control';
  return 'other';
}

/** The caption of a group: its first element when it is a heading or `summary` text block; else null. */
function captionOf(node) {
  if (!node || node.type !== 'element' || node.raw !== undefined || attr(node, 'data-h-control') !== 'group') return null;
  const first = node.children.find((child) => child.type === 'element');
  return first && hasAttr(first, 'data-h-text') && (HEADINGS.includes(first.tag) || first.tag === 'summary') ? first : null;
}

/** A `section` with a caption is labelled by it: `id` on the caption, `aria-labelledby` on the section (§20). */
function labelSection(node) {
  const caption = captionOf(node);
  if (!caption || node.tag !== 'section') {
    removeAttr(node, 'aria-labelledby');
    return;
  }
  const id = `h-${attr(caption, 'data-h-node')}`;
  setAttr(caption, 'id', id);
  setAttr(node, 'aria-labelledby', id);
}

/** Short label of a tree item. */
function labelOf(node, instance) {
  if (hasAttr(node, 'data-h-instance')) return instance?.type || 'instance';
  if (hasAttr(node, 'data-h-media')) {
    // the caption, without the link to the viewer
    const text = plain(String(node.raw || '').replace(/<a\b[^>]*>[\s\S]*?<\/a>/gi, ' '));
    return text ? `media: ${text.length > 34 ? `${text.slice(0, 34)}…` : text}` : 'media';
  }
  if (hasAttr(node, 'data-h-text')) {
    const text = plain(node.raw || '');
    if (text) return text.length > 40 ? `${text.slice(0, 40)}…` : text;
    // no text: an image (a file field) or nothing; the reference tells the fields apart
    const image = /<img\b/i.test(node.raw || '');
    const field = attr(node, 'data-h-field');
    if (field) return `${image ? 'image' : 'empty'}: ${field}`;
    return image ? '(image)' : '(empty text)';
  }
  const control = attr(node, 'data-h-control');
  if (control) {
    const heading = node.children.find((child) => child.type === 'element' && (HEADINGS.includes(child.tag) || child.tag === 'summary'));
    const title = heading ? plain(heading.raw ?? serializeCmsHtml(heading)) : '';
    return title ? `${control}: ${title}` : control;
  }
  return node.tag;
}

/** A configured instance: has settings (a pasted or new one has none). */
function isConfigured(instance) {
  if (!instance) return false;
  if (instance.kind === 'widget' && instance.type === 'menu') return true;
  return isMap(instance.settings) && Object.keys(instance.settings).length > 0;
}

function defaultInstance(kind, type) {
  return { kind, type, configVersion: CMS_CONFIG_VERSION, settings: {}, state: null };
}

/** Placeholder text of an emptied text block (copy structure): its heading stays a heading. */
function placeholderText(node) {
  if (HEADINGS.includes(node.tag) || node.tag === 'summary') return 'Title';
  return '<p>Text</p>';
}

function element$(tag, attrs, raw, children = []) {
  const node = { type: 'element', tag, attrs, children };
  if (raw !== undefined) node.raw = raw;
  return node;
}

function findNode(container, id) {
  for (const child of container.children || []) {
    if (child.type !== 'element') continue;
    if (attr(child, 'data-h-node') === id) return { node: child, parent: container };
    const found = child.raw === undefined ? findNode(child, id) : null;
    if (found) return found;
  }
  if (container.type === 'element' && attr(container, 'data-h-node') === id) return { node: container, parent: null };
  return null;
}

function removeChild(parent, node) {
  const index = parent.children.indexOf(node);
  if (index >= 0) parent.children.splice(index, 1);
}

function walk(node, visit) {
  if (node.type === 'element') visit(node);
  if (node.raw === undefined) for (const child of node.children || []) if (child.type === 'element') walk(child, visit);
}

function idsIn(node) {
  const nodes = [];
  const instances = [];
  const media = [];
  walk(node, (element) => {
    const id = attr(element, 'data-h-node');
    if (id) nodes.push(id);
    const instance = attr(element, 'data-h-instance');
    if (instance) instances.push(instance);
    const mediaId = attr(element, 'data-h-media');
    if (mediaId) media.push(mediaId);
  });
  return { nodes, instances, media };
}

function closingIndex(source, tag, from) {
  const pattern = new RegExp(`<(/?)${tag}\\b[^>]*>`, 'gi');
  pattern.lastIndex = from;
  let depth = 1;
  let match;
  while ((match = pattern.exec(source))) {
    if (match[1]) depth--; else if (!match[0].endsWith('/>')) depth++;
    if (depth === 0) return { start: match.index, end: pattern.lastIndex };
  }
  return { start: source.length, end: source.length };
}

function parseAttributes(source) {
  const attrs = [];
  for (const match of source.matchAll(/([^\s"'>/=]+)(?:\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\s"'=<>`]+)))?/g)) {
    attrs.push([match[1].toLowerCase(), decodeEntities(match[2] ?? match[3] ?? match[4] ?? '')]);
  }
  return attrs;
}

function attr(node, name) {
  const found = node?.attrs?.find(([key]) => key === name);
  return found ? found[1] : null;
}

function hasAttr(node, name) {
  return Boolean(node?.attrs?.some(([key]) => key === name));
}

function setAttr(node, name, value) {
  const found = node.attrs.find(([key]) => key === name);
  if (found) found[1] = String(value); else node.attrs.push([name, String(value)]);
}

function removeAttr(node, name) {
  node.attrs = node.attrs.filter(([key]) => key !== name);
}

function decodeEntities(text) {
  return text.replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&amp;/g, '&');
}

function escapeAttr(value) {
  return String(value).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

function escapeText(value) {
  return String(value).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

function plain(html) {
  return decodeEntities(String(html).replace(/<[^>]*>/g, ' ')).replace(/\s+/g, ' ').trim();
}

function clone(value) {
  return value == null ? value : JSON.parse(JSON.stringify(value));
}

function isMap(value) {
  return value !== null && typeof value === 'object' && !Array.isArray(value);
}
